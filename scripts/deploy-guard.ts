/**
 * Deploy RescueGuard to Mezo testnet and record it.
 *
 *   cd contracts && npx hardhat compile && cd .. && npx tsx scripts/deploy-guard.ts
 *
 * - constructor args are the live MUSD contracts (BorrowerOperationsSignatures is read from BorrowerOperations)
 * - explicit gas: estimate x1.5, capped below Mezo's 10M block gas limit
 * - writes deployments/mezo-testnet.json and regenerates src/config/guard.ts (address, deploy block, ABI)
 * Verify afterwards: cd contracts && npx hardhat verify --network mezotestnet <address> <args...>
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execSync } from "node:child_process";
import { createPublicClient, createWalletClient, http, parseAbi, formatEther, type Abi, type Hex } from "viem";
import { mezoTestnet } from "../src/config/chains";
import { MUSD_CONTRACTS } from "../src/config/contracts";
import { loadDeployer } from "./lib/keys";

const A = MUSD_CONTRACTS.testnet;
const ARTIFACT = "contracts/artifacts/contracts/RescueGuard.sol/RescueGuard.json";

async function main() {
  const pub = createPublicClient({ chain: mezoTestnet, transport: http() });
  const deployer = loadDeployer();
  const wallet = createWalletClient({ account: deployer, chain: mezoTestnet, transport: http() });
  const art = JSON.parse(readFileSync(ARTIFACT, "utf8")) as { abi: Abi; bytecode: Hex; deployedBytecode: Hex };
  const size = (art.deployedBytecode.length - 2) / 2;
  console.log(`RescueGuard runtime size ${size} bytes (limit 24576)`);
  if (size > 24_576) throw new Error("Contract too large for Mezo");

  const bos = await pub.readContract({ address: A.BorrowerOperations, abi: parseAbi(["function borrowerOperationsSignaturesAddress() view returns (address)"]), functionName: "borrowerOperationsSignaturesAddress" });
  const args = [bos, A.TroveManager, A.PriceFeed, A.MUSD] as const;
  console.log("deployer", deployer.address, "balance", formatEther(await pub.getBalance({ address: deployer.address })), "BTC");
  console.log("args", args);

  const estimate = await pub.estimateGas({ account: deployer.address, data: (await import("viem")).encodeDeployData({ abi: art.abi, bytecode: art.bytecode, args }) });
  let gas = (estimate * 15n) / 10n;
  if (gas > 9_500_000n) gas = 9_500_000n;
  const hash = await wallet.deployContract({ abi: art.abi, bytecode: art.bytecode, args, gas });
  console.log("deploy tx", hash);
  const rc = await pub.waitForTransactionReceipt({ hash, timeout: 180_000 });
  if (rc.status !== "success" || !rc.contractAddress) throw new Error(`deploy failed: ${rc.status}`);
  console.log("RescueGuard", rc.contractAddress, "block", rc.blockNumber, "gasUsed", rc.gasUsed);

  const commit = execSync("git rev-parse HEAD").toString().trim();
  mkdirSync("deployments", { recursive: true });
  // Keep earlier deployments in the record, marked superseded (never silently overwritten).
  const prev = existsSync("deployments/mezo-testnet.json") ? JSON.parse(readFileSync("deployments/mezo-testnet.json", "utf8")) : null;
  const superseded = [
    ...(prev?.superseded ?? []),
    ...(prev?.contracts?.RescueGuard ? [{ ...prev.contracts.RescueGuard, supersededAt: new Date().toISOString(), reason: process.env.SUPERSEDE_REASON || "redeployed" }] : []),
  ];
  const record = {
    network: "mezo-testnet",
    chainId: mezoTestnet.id,
    contracts: {
      RescueGuard: {
        address: rc.contractAddress,
        deployTx: hash,
        deployBlock: Number(rc.blockNumber),
        gasUsed: rc.gasUsed.toString(),
        deployer: deployer.address,
        constructorArgs: { borrowerOperationsSignatures: bos, troveManager: A.TroveManager, priceFeed: A.PriceFeed, musd: A.MUSD },
        compiler: "solc 0.8.24, optimizer 200 runs, evmVersion london, OpenZeppelin 5.0.2",
        sourceCommit: commit,
        explorer: `https://explorer.test.mezo.org/address/${rc.contractAddress}`,
      },
    },
    deployedAt: new Date().toISOString(),
    superseded,
  };
  writeFileSync("deployments/mezo-testnet.json", JSON.stringify(record, null, 2) + "\n");
  writeGuardConfig(rc.contractAddress, Number(rc.blockNumber), bos, art.abi);
  console.log("wrote deployments/mezo-testnet.json and src/config/guard.ts");
}

export function writeGuardConfig(address: string, deployBlock: number, bos: string, abi: Abi) {
  const src = `// GENERATED by scripts/deploy-guard.ts from contracts/artifacts (RescueGuard.sol). Do not edit by hand.
// Source: contracts/contracts/RescueGuard.sol · deployment record: deployments/mezo-testnet.json
export const RESCUE_GUARD = {
  address: "${address}" as \`0x\${string}\`,
  deployBlock: ${deployBlock},
  borrowerOperationsSignatures: "${bos}" as \`0x\${string}\`,
} as const;

export const rescueGuardAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
  writeFileSync("src/config/guard.ts", src);
}

if (process.argv[1]?.endsWith("deploy-guard.ts")) main().then(() => process.exit(0)).catch((e) => { console.error(e); process.exit(1); });
